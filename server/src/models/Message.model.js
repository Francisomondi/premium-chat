import mongoose from "mongoose";

/**
 * ============================================================
 * PREMIUMCHAT MESSAGE MODEL
 * ============================================================
 *
 * Supports:
 *
 * - Text messages
 * - Future image/video messages
 * - Future locked media
 * - Message delivery
 * - Read receipts
 * - Idempotent message creation
 */

const messageSchema = new mongoose.Schema(
  {
    conversationId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Conversation",
      required: true,
      immutable: true,
    },

    senderId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      immutable: true,
    },

    /**
     * Unique identifier generated by the client.
     *
     * Prevents duplicate messages when a request
     * is retried.
     */
    clientMessageId: {
      type: String,
      required: true,
      immutable: true,
      trim: true,
      minlength: 8,
      maxlength: 100,
    },

    type: {
      type: String,
      enum: ["TEXT", "IMAGE", "VIDEO"],
      default: "TEXT",
      required: true,
    },

    content: {
      type: String,
      trim: true,
      maxlength: 5000,
      default: "",
    },

    mediaId: {
      type: mongoose.Schema.Types.ObjectId,
      default: null,
    },

    isLocked: {
      type: Boolean,
      default: false,
    },

    status: {
      type: String,
      enum: ["SENT", "DELIVERED", "READ"],
      default: "SENT",
      required: true,
    },

    deliveredAt: {
      type: Date,
      default: null,
    },

    readAt: {
      type: Date,
      default: null,
    },

    deletedAt: {
      type: Date,
      default: null,
    },
  },
  {
    timestamps: true,
    versionKey: false,
  }
);

/**
 * ============================================================
 * VALIDATION
 * ============================================================
 */

messageSchema.pre("validate", function () {
  if (this.type === "TEXT") {
    if (
      typeof this.content !== "string" ||
      !this.content.trim()
    ) {
      this.invalidate(
        "content",
        "Text messages cannot be empty."
      );
    }

    if (this.mediaId || this.isLocked) {
      this.invalidate(
        "type",
        "Text messages cannot contain locked media."
      );
    }
  }

  if (
    ["IMAGE", "VIDEO"].includes(this.type) &&
    !this.mediaId
  ) {
    this.invalidate(
      "mediaId",
      "Media messages require a media reference."
    );
  }
});

/**
 * ============================================================
 * INDEXES
 * ============================================================
 */

/**
 * Prevent duplicate messages for the same sender
 * within a conversation.
 */
messageSchema.index(
  {
    conversationId: 1,
    senderId: 1,
    clientMessageId: 1,
  },
  {
    unique: true,
    name: "unique_client_message",
  }
);

/**
 * Message history pagination.
 */
messageSchema.index(
  {
    conversationId: 1,
    createdAt: -1,
    _id: -1,
  },
  {
    name: "conversation_message_history",
  }
);

/**
 * Sender message lookup.
 */
messageSchema.index(
  {
    senderId: 1,
    createdAt: -1,
  },
  {
    name: "sender_message_history",
  }
);

/**
 * Message delivery/read tracking.
 */
messageSchema.index(
  {
    conversationId: 1,
    status: 1,
  },
  {
    name: "conversation_message_status",
  }
);

/**
 * ============================================================
 * MODEL EXPORT
 * ============================================================
 */

const Message =
  mongoose.models.Message ||
  mongoose.model(
    "Message",
    messageSchema
  );

export default Message;
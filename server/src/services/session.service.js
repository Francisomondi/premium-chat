
import mongoose from "mongoose";

import AuthSession from "../models/AuthSession.model.js";

/**
 * ============================================================
 * PREMIUMCHAT AUTHENTICATION SESSION SERVICE
 * ============================================================
 *
 * Responsibilities:
 *
 * 1. Create authentication sessions.
 * 2. Find active sessions.
 * 3. Revoke individual sessions.
 * 4. Revoke all sessions belonging to a user.
 *
 * Security:
 * - No passwords or raw JWTs are stored.
 * - Revoked sessions cannot be reused.
 * - Expired sessions are rejected.
 * - Session IDs are generated by MongoDB ObjectIds.
 *
 * Important:
 * MongoDB TTL deletion is asynchronous.
 * Always check expiration explicitly.
 */

export const SESSION_DURATION_MS = 15 * 60 * 1000;

/**
 * ============================================================
 * CREATE SESSION
 * ============================================================
 *
 * Creates a database record for a successful login.
 *
 * @param {string|ObjectId} userId
 * @returns {Promise<AuthSession>}
 */

export const createSession = async (userId) => {
  if (!mongoose.isValidObjectId(userId)) {
    throw new Error("Invalid user ID.");
  }

  const expiresAt = new Date(
    Date.now() + SESSION_DURATION_MS
  );

  return AuthSession.create({
    userId,
    expiresAt,
  });
};

/**
 * ============================================================
 * GET ACTIVE SESSION
 * ============================================================
 *
 * Returns null if the session:
 * - Does not exist.
 * - Has been revoked.
 * - Has expired.
 * - Belongs to another user.
 *
 * @param {string|ObjectId} sessionId
 * @param {string|ObjectId} userId
 * @returns {Promise<AuthSession|null>}
 */

export const getActiveSession = async (
  sessionId,
  userId
) => {
  if (
    !mongoose.isValidObjectId(sessionId) ||
    !mongoose.isValidObjectId(userId)
  ) {
    return null;
  }

  const session = await AuthSession.findOne({
    _id: sessionId,
    userId,
    revokedAt: null,
    expiresAt: {
      $gt: new Date(),
    },
  });

  if (!session) {
    return null;
  }

  return session.isActive() ? session : null;
};

/**
 * ============================================================
 * REVOKE SESSION
 * ============================================================
 *
 * Revokes one session belonging to a user.
 *
 * Safe to call multiple times.
 *
 * @returns {Promise<boolean>}
 *
 * true  = session was revoked by this call
 * false = session was missing or already revoked
 */

export const revokeSession = async (
  sessionId,
  userId
) => {
  if (
    !mongoose.isValidObjectId(sessionId) ||
    !mongoose.isValidObjectId(userId)
  ) {
    return false;
  }

  const result = await AuthSession.updateOne(
    {
      _id: sessionId,
      userId,
      revokedAt: null,
    },
    {
      $set: {
        revokedAt: new Date(),
      },
    }
  );

  return result.modifiedCount === 1;
};

/**
 * ============================================================
 * REVOKE ALL USER SESSIONS
 * ============================================================
 *
 * Useful for:
 * - Password changes.
 * - Account compromise.
 * - Account suspension.
 * - Administrative security actions.
 *
 * @returns {Promise<number>}
 *
 * Number of sessions revoked.
 */

export const revokeAllUserSessions = async (
  userId
) => {
  if (!mongoose.isValidObjectId(userId)) {
    throw new Error("Invalid user ID.");
  }

  const result = await AuthSession.updateMany(
    {
      userId,
      revokedAt: null,
    },
    {
      $set: {
        revokedAt: new Date(),
      },
    }
  );

  return result.modifiedCount;
};
